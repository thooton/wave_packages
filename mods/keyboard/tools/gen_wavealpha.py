#!/usr/bin/env python3
"""Generate WaveAlpha.java (engine call gate) and the NativeAlphaInput compile stub
from the decompiled NativeAlphaInput.java signatures.

usage: gen_wavealpha.py <NativeAlphaInput.java> <java-out-dir> <stubs-out-dir>"""
import re, sys, os

src, jout, sout = sys.argv[1:4]
pkg = 'com.nuance.flext9_OEM.input'
sigs = re.findall(r'public static native (\S+) (xt9input_alpha_\w+)\(([^)]*)\);', open(src).read())

# Calls with dedicated handling in WaveSpec.
SPECIAL = {
    'xt9input_alpha_processKey': 'return WaveSpec.processKey(a0, a1, a2, a3);',
    'xt9input_alpha_buildSelectionList': 'return WaveSpec.buildSelectionList(a0);',
    'xt9input_alpha_getKeyCount': 'return WaveSpec.getKeyCount(a0);',
    'xt9input_alpha_getDefaultWordIndex': 'return WaveSpec.getDefaultWordIndex(a0);',
    'xt9input_alpha_getWord': 'return WaveSpec.getWord(a0, a1, a2, a3, a4, a5);',
    'xt9input_alpha_getInlineText': 'return WaveSpec.getInlineText(a0, a1, a2);',
    'xt9input_alpha_isInlineKnown': 'return WaveSpec.isInlineKnown(a0);',
    'xt9input_alpha_wordSelected': 'WaveSpec.wordSelected(a0, a1, a2);',
    'xt9input_alpha_clearAllKeys': 'return WaveSpec.clearAllKeys(a0);',
}

def params(p):
    p = p.strip()
    if not p:
        return []
    out = []
    for i, part in enumerate(p.split(', ')):
        typ = part.rsplit(' ', 1)[0]
        out.append((typ, 'a%d' % i))
    return out

head = ('package %s;\n\nimport android.content.Context;\nimport android.graphics.Point;\nimport android.os.Trace;\nimport java.util.List;\n\n' % pkg)
w = [head,
     '/**\n * Generated by tools/gen_wavealpha.py. Every XT9 engine call in AlphaInput goes through\n'
     ' * here (smali call sites retargeted from NativeAlphaInput) so that WaveSpec can run the\n'
     ' * engine ahead of time on its own thread and keep all engine calls serialized.\n */\n',
     'public final class WaveAlpha {\n    private WaveAlpha() { }\n']
stub = [head, '/** Compile stub of the stock class (not packaged). */\npublic final class NativeAlphaInput {\n']
names = []
for ret, name, p in sigs:
    ps = params(p)
    decl = ', '.join('%s %s' % t for t in ps)
    args = ', '.join(n for _, n in ps)
    stub.append('    public static native %s %s(%s);\n' % (ret, name, decl))
    w.append('\n    public static %s %s(%s) {\n' % (ret, name, decl))
    if name in SPECIAL:
        w.append('        %s\n    }\n' % SPECIAL[name])
        continue
    call = 'NativeAlphaInput.%s(%s);' % (name, args)
    short = name.replace('xt9input_alpha_', '')
    names.append(short)
    w.append('        WaveSpec.enter(%d);\n        Trace.beginSection("xt9.%s");\n        try {\n' % (len(names) - 1, short))
    w.append('            %s%s\n' % ('' if ret == 'void' else 'return ', call))
    w.append('        } finally {\n            Trace.endSection();\n            WaveSpec.exit(%d);\n        }\n    }\n' % (len(names) - 1))
w.append('\n    /** Names of the calls by the id passed to WaveSpec.enter/exit. */\n    static final String[] NAMES = {\n')
for i in range(0, len(names), 4):
    w.append('        ' + ' '.join('"%s",' % n for n in names[i:i + 4]) + '\n')
w.append('    };\n')
w.append('}\n')
stub.append('}\n')
d = os.path.join(jout, *pkg.split('.')); os.makedirs(d, exist_ok=True)
open(os.path.join(d, 'WaveAlpha.java'), 'w', newline='\n').write(''.join(w))
d = os.path.join(sout, *pkg.split('.')); os.makedirs(d, exist_ok=True)
open(os.path.join(d, 'NativeAlphaInput.java'), 'w', newline='\n').write(''.join(stub))
print(len(sigs), 'engine calls')
